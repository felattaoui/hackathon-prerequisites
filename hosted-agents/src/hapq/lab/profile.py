"""Lab profile: endpoints and ids produced by a lab deployment (no secrets).

Written by `hapq lab deploy` to config/lab-<env>.local.toml (git-ignored). Scenario code reads it so the
same scenarios can target A (public) or B (private).
"""
from __future__ import annotations

import json
import tomllib
from dataclasses import asdict, dataclass, field
from pathlib import Path

from ..config import REPO_ROOT


@dataclass
class LabProfile:
    environment: str                  # "A" or "B"
    region: str
    account_name: str
    account_id: str
    project_names: list[str]
    project_endpoints: list[str]
    project_principal_ids: list[str]
    model_deployment: str
    app_insights_app_id: str
    app_insights_id: str
    mcp_url: str
    mcp_audience: str                 # api://<appId>
    mcp_app_id: str
    acr_name: str = ""
    extra: dict = field(default_factory=dict)

    @staticmethod
    def path(environment: str) -> Path:
        return REPO_ROOT / "config" / f"lab-{environment.lower()}.local.toml"

    def write(self) -> Path:
        p = self.path(self.environment)
        lines = ["# Generated by `hapq lab deploy`. Local only (git-ignored). No secrets."]
        lines += [f"{k} = {json.dumps(v)}" for k, v in asdict(self).items() if k != "extra"]
        p.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return p

    @classmethod
    def load(cls, environment: str) -> "LabProfile":
        p = cls.path(environment)
        if not p.exists():
            raise FileNotFoundError(f"{p.name} not found: lab {environment} is not deployed (or not by this kit)")
        return cls(**tomllib.loads(p.read_text(encoding="utf-8")))
